#!/usr/bin/env node
/**
 * Generate `src/palettes.generated.ts` from the Minimalist Chrome theme
 * collection. Each theme directory must contain a Chrome manifest.json whose
 * `theme.colors` block carries the palette this plugin adapts to DSH.
 *
 * Usage: node scripts/generate-palettes.mjs [path-to-temas-chrome]
 * (default: ../temas-chrome relative to this repository root)
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const sourceArg = process.argv[2]
const sourceDir = resolve(sourceArg ?? join(here, '..', '..', 'temas-chrome'))

if (!existsSync(sourceDir)) {
  console.error(`Theme source directory not found: ${sourceDir}`)
  console.error('Pass the path to the temas-chrome collection as the first argument.')
  process.exit(1)
}

/** Chrome manifest color keys consumed by the adapter, in stable order. */
const COLOR_KEYS = [
  'frame',
  'toolbar',
  'omnibox_background',
  'omnibox_text',
  'bookmark_text',
  'tab_text',
  'tab_background_text',
  'tab_background_text_inactive',
  'ntp_background',
  'ntp_text',
  'ntp_link',
  'ntp_section',
  'button_background',
  'toolbar_button_icon',
]

const slug = (name) => name
  .replace(/^Minimalist\s+/, '')
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/(^-|-$)/g, '')

const themes = []
for (const entry of readdirSync(sourceDir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
  if (!entry.isDirectory()) continue
  const manifestPath = join(sourceDir, entry.name, 'manifest.json')
  if (!existsSync(manifestPath)) continue
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
  const colors = manifest.theme?.colors
  if (colors === undefined) {
    console.warn(`Skipping "${entry.name}": manifest has no theme.colors block.`)
    continue
  }
  const picked = {}
  for (const key of COLOR_KEYS) {
    const value = colors[key]
    if (Array.isArray(value) && value.length === 3) picked[key] = value
  }
  themes.push({
    id: slug(manifest.name ?? entry.name),
    title: manifest.name ?? entry.name,
    version: manifest.version ?? '0.0.0',
    colors: picked,
  })
}

if (themes.length === 0) {
  console.error('No Chrome theme manifests found — nothing generated.')
  process.exit(1)
}

const banner = `/**
 * Generated by scripts/generate-palettes.mjs from the Minimalist Chrome theme
 * collection (${themes.length} themes). Do not edit by hand; re-run the script
 * after changing the collection.
 */
`

const body = `export interface MinimalistPalette {
  id: string
  title: string
  version: string
  colors: Record<string, [number, number, number]>
}

export const MINIMALIST_PALETTES: readonly MinimalistPalette[] = Object.freeze([
${themes.map((t) => `  Object.freeze({
    id: ${JSON.stringify(t.id)},
    title: ${JSON.stringify(t.title)},
    version: ${JSON.stringify(t.version)},
    colors: Object.freeze({
${Object.entries(t.colors).map(([k, v]) => `      ${k}: [${v.join(', ')}] as [number, number, number],`).join('\n')}
    }),
  })`).join(',\n')},
])
`

const outPath = join(here, '..', 'src', 'palettes.generated.ts')
writeFileSync(outPath, banner + body, 'utf8')
console.log(`Wrote ${outPath} with ${themes.length} themes:`)
for (const t of themes) console.log(`  - ${t.id} (${t.title})`)
